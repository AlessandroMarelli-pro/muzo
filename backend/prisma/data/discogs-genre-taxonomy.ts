/** Same normalization the backend applies before persisting a genre/style name. */
export const normalizeTaxonomyName = (name: string): string => name.trim().toLowerCase();

export interface FlatTaxonomy {
  /** normalized genre names */
  genres: string[];
  /** normalized style name -> normalized parent genre name (first parent wins) */
  subgenres: Map<string, string>;
}

/** Flattens the taxonomy to the normalized, de-duplicated form used for seeding. */
export const flattenTaxonomy = (): FlatTaxonomy => {
  const genres = new Set<string>();
  const subgenres = new Map<string, string>();

  for (const [genre, styles] of Object.entries(DISCOGS_GENRE_TAXONOMY)) {
    const g = normalizeTaxonomyName(genre);
    genres.add(g);
    for (const style of styles) {
      const s = normalizeTaxonomyName(style);
      if (!subgenres.has(s)) subgenres.set(s, g);
    }
  }

  return { genres: [...genres], subgenres };
};
